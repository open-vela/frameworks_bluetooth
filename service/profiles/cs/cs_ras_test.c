/**
 * @brief LE CS Subevent Result Event
 *
 * This event is generated when the local Controller has results to report for a CS
 * (Channel Sounding) subevent during the CS procedure. Depending on the number of CS steps in the CS
 * subevent, the Controller may choose to report complete or partial results. If the number of CS steps exceeds
 * the maximum HCI event size, the Controller may report further results using the HCI_LE_CS_Subevent_Result_Continue event.
 *
 * **General Overview**:
 * - When the `Connection_Handle` is set to 0x0FFF, the `Config_ID` and `Start_ACL_Conn_Event_Counter` parameters
 *   are ignored.
 * - The `Start_ACL_Conn_Event_Counter` parameter indicates the starting ACL connection event count to which the CS
 *   event results reported in this HCI event are anchored.
 * - The `Procedure_Counter` parameter indicates the associated CS procedure count for the results reported in this event.
 * - The `Frequency_Compensation` parameter is a value used by the initiator device to align the timing of CS steps and
 *   transmit frequencies.
 * - The `Reference_Power_Level` is the power level in dBm used during the CS procedure. If the reference power level
 *   is not available during a subevent, it is set to `0x7F`.
 * - The event can report either complete or partial results, and more results can be sent in continuation events when the
 *   CS steps exceed the maximum event size.
 * - The event also includes various parameters related to the CS steps, such as the number of steps, step modes, channels,
 *   and specific data for each step.
 *
 * **Abort Reason**:
 * - The `Abort_Reason` field specifies why the CS procedure or subevent was aborted, if applicable.
 *
 * **Event Parameters**:
 *
 * - `Subevent_Code` (1 octet) :
 *   - Value `0x31` indicates this is an HCI_LE_CS_Subevent_Result event.
 *
 * - `Connection_Handle` (2 octets):
 *   - `0x0000 to 0x0EFF`: Connection handle associated with the ACL connection.
 *   - `0x0FFF`: Indicates a CS test; other values are reserved for future use.
 *
 * - `Config_ID` (1 octet):
 *   - A configuration identifier for the CS procedure. The value ranges from `0` to `3`.
 *
 * - `Start_ACL_Conn_Event_Counter` (2 octets):
 *   - Indicates the starting ACL connection event count for the results in this event.
 *
 * - `Procedure_Counter` (2 octets):
 *   - CS procedure count indicating the number of procedures since the CS procedure started.
 *   - Range: `0x0000` to `0xFFFF`.
 *
 * - `Frequency_Compensation` (2 octets):
 *   - Fractional frequency offset (FFO) in units of `0.01 ppm` (signed 15-bit integer).
 *   - Range: `-100 ppm (0x58F0)` to `+100 ppm (0x2710)`.
 *   - `0xC000`: Frequency compensation not available (or the role is not initiator).
 *
 * - `Reference_Power_Level` (1 octet):
 *   - Reference power level in dBm.
 *   - Range: `-127 to 20 dBm`.
 *   - `0x7F`: Reference power level not applicable.
 *
 * - `Procedure_Done_Status` (1 octet):
 *   - Indicates the status of the CS procedure.
 *   - Bits 0-3:
 *     - `0x0`: All results complete.
 *     - `0x1`: Partial results, more to follow.
 *     - `0xF`: Procedure aborted.
 *   - Bits 4-7: Reserved for future use.
 *
 * - `Subevent_Done_Status` (1 octet):
 *   - Indicates the status of the CS subevent.
 *   - Bits 0-3:
 *     - `0x0`: All results complete.
 *     - `0x1`: Partial results, more to follow.
 *     - `0xF`: Subevent aborted.
 *   - Bits 4-7: Reserved for future use.
 *
 * - `Abort_Reason` (1 octet):
 *   - Specifies the reason for aborting the procedure or subevent, if applicable.
 *   - Bits 0-3: Abort reason for the procedure.
 *   - Bits 4-7: Abort reason for the subevent.
 *
 * - `Num_Antenna_Paths` (1 octet):
 *   - Indicates the number of antenna paths used during the CS procedure.
 *   - Range: `0x00` (no phase measurement) to `0x04` (up to four antenna paths).
 *
 * - `Num_Steps_Reported` (1 octet):
 *   - Number of CS steps reported in this event.
 *   - Range: `0x00` to `0xA0` (up to 160 steps).
 *
 * - `Step_Mode[i]` (Num_Steps_Reported × 1 octet):
 *   - The CS mode for each CS step.
 *   - Values: `0x00 to 0x03` (various modes).
 *
 * - `Step_Channel[i]` (Num_Steps_Reported × 1 octet):
 *   - The channel used for each CS step.
 *   - Valid channels: `0x00 to 0x4E` (refer to [Vol 6] Part A, Section 2 for details).
 *
 * - `Step_Data_Length[i]` (Num_Steps_Reported × 1 octet):
 *   - The length of mode- and role-specific information for each step.
 *   - Range: `0x00 to 0xFF`.
 *
 * - `Step_Data[i]` (Σi(Step_Data_Length[i]) octets):
 *   - The mode- and role-specific information for each step.
 *   - The structure of this data varies based on the CS mode and role of the local device.
 *
 * **Procedure Done and Subevent Done Status Combinations**:
 * The valid combinations of `Procedure_Done_Status` and `Subevent_Done_Status` are:
 *
 * | Procedure_Done_Status (Bits 0 to 3) | Allowed Subevent_Done_Status (Bits 0 to 3) |
 * |------------------------------------|-------------------------------------------|
 * | `0x0`                              | `0x0`, `0xF`                             |
 * | `0x1`                              | `0x0`, `0x1`, `0xF`                      |
 * | `0xF`                              | `0x0`, `0xF`                             |
 *
 * **Mode Role Specific Information**:
 * The information reported in `Step_Data` varies based on the CS mode and the role of the device.
 *
 * - **Mode 0** (Initiator):
 *   - `Packet_Quality`, `Packet_RSSI`, `Packet_Antenna`, `Measured_Freq_Offset`
 * - **Mode 0** (Reflector):
 *   - `Packet_Quality`, `Packet_RSSI`, `Packet_Antenna`
 * - **Mode 1** (Initiator):
 *   - `Packet_Quality`, `Packet_NADM`, `Packet_RSSI`, `ToA_ToD_Initiator`, `Packet_Antenna`
 * - **Mode 1** (Reflector):
 *   - `Packet_Quality`, `Packet_NADM`, `Packet_RSSI`, `ToD_ToA_Reflector`, `Packet_Antenna`
 * - **Mode 2** (Initiator or Reflector):
 *   - `Antenna_Permutation_Index`, `Tone_PCT[k]`, `Tone_Quality_Indicator[k]`
 * - **Mode 3** (Initiator):
 *   - `Packet_Quality`, `Packet_NADM`, `Packet_RSSI`, `ToA_ToD_Initiator`, `Packet_Antenna`,
 *     `Antenna_Permutation_Index`, `Tone_PCT[k]`, `Tone_Quality_Indicator[k]`
 * - **Mode 3** (Reflector):
 *   - `Packet_Quality`, `Packet_NADM`, `Packet_RSSI`, `ToD_ToA_Reflector`, `Packet_Antenna`,
 *     `Antenna_Permutation_Index`, `Tone_PCT[k]`, `Tone_Quality_Indicator[k]`
 *
 * **Mode and Role Specific Information Parameters**:
 * For each CS mode, specific parameters like `Packet_Quality`, `Packet_RSSI`, `Packet_Antenna`, etc., are included.
 *
 * **Tone Quality Indicator**:
 * - Bits 0-3: Tone quality values (`0x0` to `0x3`).
 * - Bits 4-7: Tone extension slot information (`0x0` to `0x2`).
 *
 * **Other Parameters**:
 * - `Packet_Quality`, `Packet_NADM`, `Packet_RSSI`, `Packet_Antenna`: These parameters represent the quality of the communication packet,
 *   the NADM (Normalized Antenna Diversity Measure), received signal strength indication (RSSI), and the antenna used for the transmission.
 *
 * **Example of Event Data**:
 * - If the number of reported CS steps exceeds the maximum HCI event size, multiple continuation events may follow.
 */
