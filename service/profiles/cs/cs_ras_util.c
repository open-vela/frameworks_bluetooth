#include "cs_ras_util.h"

const char* cs_log_to_hex_str(const void* buf, size_t len)
{
    static const char hex[] = "0123456789abcdef";
    static char str[1024];
    const uint8_t* b = buf;
    size_t i;

    len = MIN(len, (sizeof(str) - 1) / 2);

    for (i = 0; i < len; i++) {
        str[i * 2] = hex[b[i] >> 4];
        str[i * 2 + 1] = hex[b[i] & 0xf];
    }

    str[i * 2] = '\0';

    return str;
}